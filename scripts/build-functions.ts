import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

/**
 * Bundles the game rules, zod and the JSON catalog into one dependency-free ES
 * module for the Edge Functions. Deno then needs no import maps, file
 * extensions or npm specifiers to run exactly the code the game runs.
 */
export const FUNCTION_BUNDLE = fileURLToPath(
  new URL('../supabase/functions/_shared/game.js', import.meta.url),
);

export async function buildFunctionBundle(outfile: string = FUNCTION_BUNDLE): Promise<void> {
  await build({
    entryPoints: [fileURLToPath(new URL('../src/server/rules.ts', import.meta.url))],
    outfile,
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    banner: {
      // Deno reads the types of this generated module from the hand-written game.d.ts.
      js: [
        '// Generated by `npm run build:functions` from src/server. Do not edit.',
        '// @ts-self-types="./game.d.ts"',
      ].join('\n'),
    },
    logLevel: 'warning',
  });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await buildFunctionBundle();
  console.log(`[functions] bundle written to ${FUNCTION_BUNDLE}`);
}
