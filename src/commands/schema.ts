import { z } from 'zod';
import {
  amountBagSchema,
  archiveChangeSchema,
  depotChangeSchema,
  MISSION_DESCRIPTION_LIMIT,
  MISSION_MAX_DAYS,
  MISSION_TITLE_LIMIT,
  missionDifficultySchema,
  missionResultSchema,
  npcSpriteSchema,
  npcStatusSchema,
  researchSchema,
  shopItemSchema,
  npcAttributesSchema,
  skillLevelSchema,
} from '../model/schema';
import { IMAGE_KINDS } from '../systems/GameImages';

// Every action in the game as plain data: it can be logged, sent to a server
// and validated there. Names are checked by the systems (not here) so an empty
// or duplicate name keeps its specific message instead of a generic refusal.

const ref = z.string().min(1);
/** Id of a record the command creates, generated by the client (see `newId`). */
const newRecordId = z.string().regex(/^[a-z0-9_-]{1,64}$/);
const signedBag = z.record(z.string(), z.number().int());
/** A delta that gives or takes, never both at once. */
const oneWayBag = signedBag.refine((bag) => {
  const amounts = Object.values(bag);
  return amounts.every((n) => n >= 0) || amounts.every((n) => n <= 0);
}, 'adds and removes coins at once');
const optionalText = z.string().optional();

export const walletRefSchema = z.discriminatedUnion('kind', [
  z.object({ kind: z.literal('camp') }),
  z.object({ kind: z.literal('character'), characterId: ref }),
]);

const materialFields = {
  name: z.string(),
  category: ref,
  icon: optionalText,
  description: optionalText,
};

const characterFields = {
  name: z.string(),
  color: z.string().regex(/^#[0-9a-fA-F]{6}$/),
  portrait: optionalText,
};

const npcFields = {
  name: z.string(),
  title: z.string(),
  portrait: optionalText,
  description: z.string(),
  skills: z.record(z.string(), skillLevelSchema),
  attributes: npcAttributesSchema.optional(),
  wage: z.number().nonnegative().optional(),
  /** `null` goes back to the automatic pick; left out, an edit keeps the current one. */
  sprite: npcSpriteSchema.nullable().optional(),
};

const missionFields = {
  title: z.string().max(MISSION_TITLE_LIMIT),
  requester: z.string().max(MISSION_TITLE_LIMIT),
  location: z.string().max(MISSION_TITLE_LIMIT),
  description: z.string().max(MISSION_DESCRIPTION_LIMIT),
  reward: amountBagSchema,
  days: z.number().int().min(1).max(MISSION_MAX_DAYS),
  difficulty: missionDifficultySchema,
};

const [inProgress, completed] = researchSchema.options;
const researchDraftSchema = z.discriminatedUnion('status', [
  inProgress.omit({ id: true }),
  completed.omit({ id: true }),
]);

// The name is checked by the system, so a blank one keeps its own message.
const [materialItem, equipmentItem] = shopItemSchema.options;
const shopItemFieldsSchema = z.discriminatedUnion('kind', [
  materialItem.omit({ id: true, discountPercent: true, image: true }),
  equipmentItem
    .omit({ id: true, discountPercent: true, image: true, name: true })
    .extend({ name: z.string() }),
]);

const command = <T extends string, S extends z.ZodRawShape>(type: T, shape: S) =>
  z.object({ type: z.literal(type), ...shape });

export const gameCommandSchema = z.discriminatedUnion('type', [
  // Structures
  command('build', { slotId: ref, buildingId: ref }),
  command('upgrade', { slotId: ref }),
  command('advance_days', { days: z.number().int().positive().max(3650) }),
  command('force_building', { slotId: ref, buildingId: ref, level: z.number().int().positive() }),
  command('remove_building', { slotId: ref }),
  // Coins
  /** Kept for pages opened before `take_coins`: only adds or only removes, never both. */
  command('adjust_coins', { wallet: walletRefSchema, delta: oneWayBag }),
  command('give_coins', { wallet: walletRefSchema, coins: amountBagSchema }),
  /** Removes the value of `coins`, paying with change from whatever the wallet holds. */
  command('take_coins', { wallet: walletRefSchema, coins: amountBagSchema }),
  command('deposit', { characterId: ref, coins: amountBagSchema }),
  command('transfer_coins', { from: walletRefSchema, to: walletRefSchema, coins: amountBagSchema }),
  command('consolidate_wallet', { wallet: walletRefSchema }),
  // Materials
  command('add_material', {
    id: newRecordId,
    ...materialFields,
    quantity: z.number().int().nonnegative(),
  }),
  command('update_material', { materialId: ref, ...materialFields }),
  command('remove_material', { materialId: ref }),
  command('adjust_material', { materialId: ref, delta: z.number().int() }),
  command('add_material_category', { id: newRecordId, name: z.string() }),
  command('rename_material_category', { categoryId: ref, name: z.string() }),
  command('remove_material_category', { categoryId: ref }),
  // Research
  command('add_research', { id: newRecordId, draft: researchDraftSchema }),
  command('update_research', { researchId: ref, draft: researchDraftSchema }),
  command('complete_research', { researchId: ref }),
  command('remove_research', { researchId: ref }),
  command('add_research_category', { id: newRecordId, name: z.string() }),
  command('rename_research_category', { categoryId: ref, name: z.string() }),
  command('remove_research_category', { categoryId: ref }),
  // Influence
  command('set_influence', { worldId: ref, value: z.number() }),
  // Characters
  command('add_character', { id: newRecordId, ...characterFields }),
  command('update_character', { characterId: ref, ...characterFields }),
  command('remove_character', { characterId: ref }),
  // Online membership: only the server runs these, while it links or unlinks a player.
  command('character_join', { id: newRecordId, ...characterFields }),
  command('character_claim', { characterId: ref }),
  command('character_release', { characterId: ref }),
  // NPCs
  command('npc_create', { id: newRecordId, ...npcFields }),
  command('npc_update', { npcId: ref, ...npcFields, status: npcStatusSchema }),
  command('npc_remove', { npcId: ref }),
  command('npc_set_home', { npcId: ref, slotId: ref.nullable() }),
  command('npc_assign_job', {
    npcId: ref,
    slotId: ref,
    activityId: ref,
    researchId: ref.optional(),
  }),
  command('npc_unassign', { npcId: ref }),
  // Missions (Guilda)
  command('mission_create', { id: newRecordId, ...missionFields }),
  command('mission_update', { missionId: ref, ...missionFields }),
  command('mission_remove', { missionId: ref }),
  command('mission_take_party', { missionId: ref }),
  command('mission_send_npcs', { missionId: ref, npcIds: z.array(ref).min(1).max(50) }),
  command('mission_resolve', {
    missionId: ref,
    result: missionResultSchema,
    injuredNpcIds: z.array(ref).max(50).default([]),
  }),
  // Entreposto shop (master only)
  command('shop_item_create', { id: newRecordId, item: shopItemFieldsSchema }),
  command('shop_item_update', { itemId: ref, item: shopItemFieldsSchema }),
  command('shop_item_remove', { itemId: ref }),
  command('shop_set_promotion', {
    itemId: ref,
    discountPercent: z.number().int().min(1).max(90).nullable(),
  }),
  // Photos (the master's forms send them with the other fields too)
  command('set_image', {
    target: z.object({ kind: z.enum(IMAGE_KINDS), id: ref }),
    image: optionalText,
  }),
  // Arquivo de registros: the records live apart; this only writes what changed to the log.
  command('archive_log', { change: archiveChangeSchema }),
  command('depot_log', { change: depotChangeSchema }),
]);

export type GameCommand = z.infer<typeof gameCommandSchema>;
export type CommandType = GameCommand['type'];

export type Actor = { role: 'master' } | { role: 'player'; characterId?: string | undefined };

export interface CommandContext {
  actor: Actor;
  /**
   * Set only by the game function while it links or unlinks a player: the
   * membership commands need it, so no client can send them as a plain command.
   */
  membership?: true;
}
